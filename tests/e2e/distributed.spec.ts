test('Fencing rejects the stale client after lease expiration and a newer resource write', async ({
  page,
}) => {
  await openCourse(page, 'distributed-locks')
  const scenario = async () => {
    await click(page, '申请带单调 token 的租约')
    await click(page, '暂停当前客户端')
    for (let i = 0; i < 3; i++) await click(page, '租约服务推进一秒')
    await select(page, 'selected', 'T2')
    await click(page, '申请带单调 token 的租约')
    await fill(page, 'value', '20')
    await click(page, '携带局部 token 写受保护资源')
    await select(page, 'selected', 'T1')
    await click(page, '恢复当前客户端')
    await fill(page, 'value', '99')
    await click(page, '携带局部 token 写受保护资源')
  }
  await scenario()
  await expect(metric(page, '资源最终值')).toHaveText('99')
  await select(page, 'mode', 'fenced')
  await scenario()
  await expect(metric(page, '资源最终值')).toHaveText('20')
  await finishCourse(page, /资源原子拒绝较旧 token/)
})
