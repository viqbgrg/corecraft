import { expect, test } from '@playwright/test'
import { click, fill, finishCourse, metric, openCourse, select } from './course-helpers'
test('CAP register compares minority rejection, local conflicts and eventual repair', async ({ page }) => {
  await openCourse(page, 'distributed-consistency')
  await click(page, '制造 A | B,C 网络分区')
  await click(page, '按当前协议执行写入')
  await expect(metric(page, '仲裁不足请求数')).toHaveText('1')
  await select(page, 'mode', 'local')
  await click(page, '制造 A | B,C 网络分区')
  await click(page, '按当前协议执行写入')
  await select(page, 'selected', 'B')
  await fill(page, 'value', '2')
  await click(page, '按当前协议执行写入')
  await click(page, '恢复网络通信')
  await click(page, '执行全组反熵修复')
  await expect(metric(page, '当前不同值数量')).toHaveText('1')
  await finishCourse(page, /系统能够按协议收敛/)
})
