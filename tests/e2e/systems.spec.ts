test('TLS identity failure prevents delivery despite equal shared values', async ({ page }) => {
  await open(page, 'tls')
  await page.getByLabel('服务器证书情形').selectOption('wrong-host')
  await page.getByRole('button', { name: '运行握手并尝试交付' }).click()
  await expect(metric(page, '客户端共享值')).toHaveText('2')
  await expect(metric(page, '服务器共享值')).toHaveText('2')
  await expect(metric(page, '应用收到的文字')).toHaveText('未交付')
  await expect(page.locator('.experiment-feedback')).toContainText('证书身份验证失败')
  await page.getByLabel('服务器证书情形').selectOption('valid')
  await page.getByLabel('握手途中改动').selectOption('finished')
  await page.getByRole('button', { name: '运行握手并尝试交付' }).click()
  await expect(page.locator('.experiment-feedback')).toContainText('Finished 验证失败')
  await page.getByLabel('握手途中改动').selectOption('none')
  await page.getByRole('button', { name: '运行握手并尝试交付' }).click()
  await expect(metric(page, '应用收到的文字')).toHaveText('hello')
  await page.getByRole('button', { name: '对比四种证书的验证结果' }).click()
  await finish(page, /拒绝应用数据交付/)
})
